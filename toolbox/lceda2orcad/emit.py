"""生成 OrCAD 库 XML 以及在 Capture 里加载它的 TCL 脚本。

Capture 的 Command Window 逐行求值，多行 if/proc 会被拆散，所以所有逻辑都放进
proc，由 TCL 的 source 一次性载入。生成的 TCL 必须是纯 ASCII：Command Window 按
GBK 解码 puts 输出，UTF-8 中文会变乱码并破坏 TCL 解析。
"""

from __future__ import annotations

from pathlib import Path

from .olbxml import SnapReport, build_lib_xml

CDS_ROOT = "C:/orcad/Cadence/SPB_17.4"
REF_OLB = f"{CDS_ROOT}/tools/capture/library/ElectroMechanical.olb"
OLB_XSD = f"{CDS_ROOT}/tools/capture/tclscripts/capDB/olb.xsd"

PLACE_TEMPLATE = None  # 摆放逻辑已并入 LIB_TEMPLATE 的 lceda2orcadPlace


def _tcl_path(path: Path) -> str:
    return str(path.resolve()).replace("\\", "/")


def _ascii_safe(text: str) -> str:
    return text.encode("ascii", errors="backslashreplace").decode("ascii")


LIB_TEMPLATE = r'''# generated by lceda2orcad -- ASCII only (Command Window decodes as GBK)

set ::lcedaXml "{xml}"
set ::lcedaOlb "{olb}"

# Package names in this library, in library order. The Accessories menu reads
# this to build one "Place <pkg>" entry per part without reinstalling itself.
set ::lcedaPkgs [list {pkgs}]

# LCSC 编号 -> 包名。lceda2orcadAdd 用它把 C2040 翻成 RP2040，因为 PlacePartEx
# 吃的是包名，不是立创编号。
array unset ::lcedaByLcsc
{lcscmap}

# Capture holds the .olb open in its master session once you place from it,
# which blocks the rebuild. Cadence frees it the same way
# (OrHandlerUnifiedSearch.tcl:196): RemoveLib drops the session handle, unless
# the user has the .olb open in the Project Manager tree -- nothing frees that.
proc lceda2orcadReleaseRaw {{}} {{
    set lSession $::DboSession_s_pDboSession
    DboSession -this $lSession
    set lState [DboState]
    set lPath [DboTclHelper_sMakeCString $::lcedaOlb]
    set lLib [$lSession GetOpenLib $lPath $lState]
    DboTclHelper_sDeleteCString $lPath
    $lState -delete
    if {{$lLib == "NULL"}} {{ return 1 }}
    if {{[capIsDesignOpened $::lcedaOlb] == 1}} {{ return 0 }}
    $lSession RemoveLib $lLib
    return 1
}}

proc lceda2orcadRelease {{}} {{
    if {{[catch {{lceda2orcadReleaseRaw}} lRes]}} {{
        puts "lceda2orcad: release skipped: $lRes"
        return 1
    }}
    return $lRes
}}

proc lceda2orcadImport {{}} {{
    catch {{set ::OrHandlerXMLImportExport::mErrorInfo ""}}
    if {{![lceda2orcadRelease]}} {{
        puts "lceda2orcad: $::lcedaOlb is open in the Project Manager -- close it and retry"
        return 0
    }}
    # Must delete first: the 3rd arg of the long form is APPEND, not overwrite.
    # The 2-arg form is what Capture's own Unified Search uses for interactive
    # placement -- passing log/tcl paths makes the translator also emit a full
    # TCL reconstruction of the library, which is what made this slow.
    if {{[file exists $::lcedaOlb] && [catch {{file delete -force $::lcedaOlb}}]}} {{
        puts "lceda2orcad: Capture holds $::lcedaOlb -- close LCEDA.OLB and retry"
        return 0
    }}
    if {{[catch {{XMATIC_XML2OLB $::lcedaXml $::lcedaOlb}} lErr]}} {{
        puts "lceda2orcad: XML2OLB raised: $lErr"
        return 0
    }}
    if {{![file exists $::lcedaOlb] || [file size $::lcedaOlb] == 0}} {{
        catch {{puts "lceda2orcad: $::OrHandlerXMLImportExport::mErrorInfo"}}
        puts "lceda2orcad: FAILED"
        return 0
    }}
    puts "lceda2orcad: OK -> $::lcedaOlb ([file size $::lcedaOlb] bytes)"
    return 1
}}

# PlacePartEx signature (from the SWIG arg-error strings in Capture.exe):
#   aLibraryName aPackageName aDeviceDesignator aIsConvert aProp aValue \
#   bShowErrorPopup
# so the bare 0 is aIsConvert, not a display flag.
#
# pPropNames/pPropValues (args 5-6) set properties on the *placed instance*.
# We deliberately leave them empty: an instance-level override appears to not
# inherit the symbol's "Value Only" display setting, which is why the value
# came out hidden. The library symbol already carries PartValue = the package
# name plus a SymbolDisplayProp for Value with display type 1 (= Value Only,
# per the Display Format radio group in Capture.exe), so inheriting is both
# correct and enough. Capture's own PWL extractor places the same way --
# OrHandlerCapPSpicePWLExtractor.tcl:438 passes "" "" for these.
#
# Callers can still pass overrides explicitly for extra properties; doing so
# may re-hide Value, so pass Value's display state yourself if you do.
proc lceda2orcadPlace {{pPkg {{pPropNames {{}}}} {{pPropValues {{}}}}}} {{
    set lFrame [DboTclHelper_sGetConstCharPtr [capGetMostRecentSchFrameID]]
    if {{[catch {{ui::SchematicActivate $lFrame}}]}} {{
        puts "lceda2orcad: no active schematic page -- open one and retry"
        return 0
    }}
    PlacePartEx $::lcedaOlb $pPkg "" 0 $pPropNames $pPropValues
}}

# Rescans every configured library, so it is slow -- only if a symbol looks stale.
proc lceda2orcadReload {{}} {{ PlacePartReloadLib }}

puts "lceda2orcad: loaded. Run:  lceda2orcadImport"
'''


def emit(symbols, out_dir, lib_name: str = "lceda") -> tuple[Path, Path, dict[str, SnapReport]]:
    """写出 <lib>.xml 与 <lib>_lib.tcl，返回两个路径和栅格对齐报告。"""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    olb_path = out_dir / f"{lib_name}.olb"
    xml_text, reports = build_lib_xml(symbols, olb_path=_tcl_path(olb_path))
    xml_path = out_dir / f"{lib_name}.xml"
    xml_path.write_text(xml_text, encoding="utf-8")

    # 先删掉旧的 .olb，这样 `file exists` 才是有效的成功判据
    if olb_path.exists():
        olb_path.unlink()

    # 包名用花括号包一层，名字里有空格或特殊字符时 list 才不会被拆开
    pkgs = " ".join("{%s}" % sym.name for sym in symbols)

    lcscmap = "\n".join(
        "set ::lcedaByLcsc(%s) {%s}" % (sym.lcsc, sym.name) for sym in symbols
    )

    body = LIB_TEMPLATE.format(
        xml=_tcl_path(xml_path),
        olb=_tcl_path(olb_path),
        pkgs=pkgs,
        lcscmap=lcscmap,
    )
    lib_tcl = out_dir / f"{lib_name}_lib.tcl"
    lib_tcl.write_text(_ascii_safe(body), encoding="ascii", newline="\n")
    return xml_path, lib_tcl, reports
